export function getTutoringNarrative(input: NarrativeInput) {
  const grade = gradeGuidance[input.grade] ?? gradeGuidance.고등;
  const subject = subjectGuidance[input.subject] ?? [input.method];
  const schoolContext = input.school
    ? `${input.school}의 시험을 준비할 때도 확인되지 않은 출제 경향을 단정하지 않고 실제 범위표, 수업 자료와 최근 답안을 기준으로 계획을 조정합니다.`
    : `${input.region} 학생의 실제 학교 범위표와 최근 답안을 확인해 내신 준비 순서를 조정합니다.`;
  return {
    diagnosis: `${pick(openings, input.key, 11)} 현재 확인된 고민은 “${input.concern}”입니다. 능력 부족으로 단정하기보다 개념 이해, 계획 실행, 숙제, 오답 복습 중 어디에서 흐름이 끊기는지 나눠 봅니다.`,
    habit: pick(grade, input.key, 23),
    subject: pick(subject, input.key, 37),
    schoolContext,
    selfStudy: `수업에서 대신 풀어 주는 것으로 끝내지 않습니다. ${input.method} 다음 수업 전에는 학생이 같은 순서를 혼자 재현하고, 실패한 지점을 질문으로 남기게 해 공부 방법 자체를 익힙니다.`,
    teacherFit: pick(teacherFit, input.key, 47),
    parentCommunication: pick(parentUpdates, input.key, 59),
    consultation: `아이에게 지금 필요한 것이 반드시 더 많은 수업은 아닐 수 있습니다. ${input.region}에서 현재 학습 기록과 목표를 먼저 살펴보고, 어떤 관리 방식과 설명이 맞는지 확인한 뒤 선생님을 연결합니다. 상담 신청만으로 수업이 확정되지는 않습니다.`,
  };
}
